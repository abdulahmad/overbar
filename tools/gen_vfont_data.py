#!/usr/bin/env python3
"""Regenerates src/vfont_data.c: the four Inter faces (Light, Regular, Medium, SemiBold) cut down to
Basic Latin, Latin-1 and a few punctuation marks (with kerning, no hinting), as C arrays.
Inter is (c) The Inter Project Authors, SIL Open Font License 1.1 (third_party/inter/OFL.txt).
usage: python3 tools/gen_vfont_data.py /path/to/Inter-{Light,Regular,Medium,SemiBold}.otf  (a directory of them)
needs: pip install fonttools"""
import os, subprocess, sys, tempfile
src = sys.argv[1]
faces = ["Light", "Regular", "Medium", "SemiBold"]
out = ["/* Generated by tools/gen_vfont_data.py: Inter, subset. (c) 2016 The Inter Project Authors, SIL OFL 1.1 (third_party/inter/OFL.txt). */",
       '#include "vfont_data.h"', ""]
with tempfile.TemporaryDirectory() as td:
    for f in faces:
        o = os.path.join(td, f + ".otf")
        subprocess.check_call(["pyftsubset", os.path.join(src, "Inter-%s.otf" % f),
            "--unicodes=U+0020-007E,U+00A0-00FF,U+2018,U+2019,U+2013,U+2014,U+2026,U+2022",
            "--layout-features=kern", "--no-hinting", "--desubroutinize", "--output-file=" + o])
        d = open(o, "rb").read()
        out.append("const unsigned char ob_vf_%s[%d] = {" % (f.lower(), len(d)))
        for i in range(0, len(d), 24):
            out.append("  " + ",".join(str(b) for b in d[i:i + 24]) + ",")
        out.append("};")
        out.append("const unsigned ob_vf_%s_len = %d;" % (f.lower(), len(d)))
        out.append("")
open(os.path.join(os.path.dirname(__file__), "..", "src", "vfont_data.c"), "w").write("\n".join(out))
